
SHOW DATABASES;

DROP DATABASE IF EXISTS dbAula20261118;

CREATE DATABASE dbAula20261118;
USE dbAula20261118;

CREATE TABLE IF NOT EXISTS tbLembrete ( 
                        ID INT AUTO_INCREMENT PRIMARY KEY,
                        TEXTO TEXT );

DELIMITER $
CREATE PROCEDURE CADASTRAR ( IN TEXTO TEXT )
BEGIN
    INSERT INTO tbLembrete ( TEXTO ) VALUES ( TEXTO );
END $
CREATE PROCEDURE CONSULTAR()
BEGIN
    SELECT ID, TEXTO FROM tbLembrete;
END $
CREATE PROCEDURE DELETAR( IN ID INT )
BEGIN
    IF ID IS NOT NULL THEN
        DELETE FROM tbTeste WHERE tbTeste.ID = ID;
    END IF;
END $
CREATE PROCEDURE ALTERAR ( IN ID INT, IN TEXTO TEXT )
BEGIN
    IF ID IS NOT NULL AND TEXTO IS NOT NULL THEN
        UPDATE tbLembrete SET tbLembrete.TEXTO= TEXTO WHERE tbLembrete.ID = ID;
    END IF;
END $
DELIMITER ;

CALL CADASTRAR("FABIANO");
CALL CADASTRAR("DAVID");
